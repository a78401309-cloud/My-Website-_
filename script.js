// 3D tilt on cards
document.querySelectorAll(
  '.about-card, .project-card, .service-card'
).forEach((card) => {
  card.classList.add('tilt');

  card.addEventListener('mousemove', (e) => {
    const rect = card.getBoundingClientRect();
    const centerX = rect.width / 2;
    const centerY = rect.height / 2;

    if (!centerX || !centerY) return;

    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;

    const rotateX = ((y - centerY) / centerY) * -6;
    const rotateY = ((x - centerX) / centerX) * 6;

    card.style.transform =
      `perspective(1000px) rotateX(${rotateX}deg) ` +
      `rotateY(${rotateY}deg) translateY(-4px)`;
  });

  card.addEventListener('mouseleave', () => {
    card.style.transform =
      'perspective(1000px) rotateX(0deg) rotateY(0deg) translateY(0)';
  });
});

// Fade-in stagger animation
if ('IntersectionObserver' in window) {
  const fadeObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;

      const element = entry.target;
      const parent = element.parentNode;

      const siblings = parent
        ? Array.from(parent.children)
        : [element];

      const delay = siblings.indexOf(element) * 100;

      element.style.transitionDelay = `${delay}ms`;

      setTimeout(() => {
        element.style.opacity = '1';
        element.style.transform = 'translateY(0)';
      }, 50);

      fadeObserver.unobserve(element);
    });
  }, {
    threshold: 0.15
  });

  document.querySelectorAll(
    '.about-card, .project-card, .skill-item, .service-card, .stat-item'
  ).forEach((el) => {
    el.style.opacity = '0';
    el.style.transform = 'translateY(30px)';
    el.style.transition = 'opacity 0.6s ease-out, transform 0.6s ease-out';

    fadeObserver.observe(el);
  });
}
