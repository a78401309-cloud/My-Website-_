// Typewriter animation
const typewriterEl = document.querySelector('.typewriter');
let typewriterQueue = [];
let typewriterIndex = 0;
let typewriterCurrentText = '';
let isDeleting = false;
let typewriterTimer = null;

function updateTypewriterText() {
  typewriterQueue = translations[currentLang].typewriter_texts;
  typewriterIndex = 0;
  typewriterCurrentText = '';
  isDeleting = false;

  if (typewriterTimer !== null) {
    clearTimeout(typewriterTimer);
  }

  if (typewriterEl) {
    typewriterEl.textContent = '';
    typewriterTick();
  }
}

function typewriterTick() {
  if (!typewriterEl || typewriterQueue.length === 0) return;

  const fullText = typewriterQueue[typewriterIndex];

  if (isDeleting) {
    typewriterCurrentText = typewriterCurrentText.slice(0, -1);
  } else {
    typewriterCurrentText = fullText.slice(
      0,
      typewriterCurrentText.length + 1
    );
  }

  typewriterEl.textContent = typewriterCurrentText;

  let delay = isDeleting ? 35 : 85;

  if (!isDeleting && typewriterCurrentText === fullText) {
    delay = 1800;
    isDeleting = true;
  } else if (isDeleting && typewriterCurrentText === '') {
    isDeleting = false;
    typewriterIndex = (typewriterIndex + 1) % typewriterQueue.length;
    delay = 400;
  }

  typewriterTimer = setTimeout(typewriterTick, delay);
}

updateTypewriterText();

// Animated counters
if ('IntersectionObserver' in window) {
  const counterObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;

      const el = entry.target;
      const target = parseInt(el.getAttribute('data-target'), 10);

      if (Number.isNaN(target)) {
        counterObserver.unobserve(el);
        return;
      }

      let current = 0;
      const increment = Math.max(1, Math.ceil(target / 40));

      const counter = setInterval(() => {
        current += increment;

        if (current >= target) {
          el.textContent = target;
          clearInterval(counter);
        } else {
          el.textContent = current;
        }
      }, 40);

      counterObserver.unobserve(el);
    });
  }, {
    threshold: 0.5
  });

  document.querySelectorAll('.stat-number').forEach((el) => {
    counterObserver.observe(el);
  });
}

