// Theme toggle
const themeToggle = document.getElementById('theme-toggle');
let isLight = false;

try {
  isLight = localStorage.getItem('Opito-theme') === 'light';
} catch (error) {
  console.warn('Theme preference could not be loaded.');
}

function applyTheme() {
  document.documentElement.setAttribute(
    'data-theme',
    isLight ? 'light' : 'dark'
  );

  if (themeToggle) {
    themeToggle.textContent = isLight ? '🌙' : '☀️';
  }

  try {
    localStorage.setItem('Opito-theme', isLight ? 'light' : 'dark');
  } catch (error) {
    console.warn('Theme preference could not be saved.');
  }
}

applyTheme();

if (themeToggle) {
  themeToggle.addEventListener('click', () => {
    isLight = !isLight;
    applyTheme();
  });
}

