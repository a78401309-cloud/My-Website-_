// Smooth scroll
document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
  anchor.addEventListener('click', function (e) {
    const href = this.getAttribute('href');

    if (!href || href === '#') return;

    const target = document.querySelector(href);

    if (target) {
      e.preventDefault();

      target.scrollIntoView({
        behavior: 'smooth',
        block: 'start'
      });
    }
  });
});

// Toast notifications
function showToast(message) {
  const toast = document.getElementById('toast');

  if (!toast) return;

  toast.textContent = message;
  toast.classList.add('show');

  if (showToast.timer) {
    clearTimeout(showToast.timer);
  }

  showToast.timer = setTimeout(() => {
    toast.classList.remove('show');
  }, 3500);
}

// Contact form — sends messages to your email using FormSubmit
const contactForm = document.getElementById('contact-form');

if (contactForm) {
  contactForm.addEventListener('submit', async function (e) {
    e.preventDefault();

    const form = this;
    const submitButton = form.querySelector(
      'button[type="submit"], input[type="submit"]'
    );

    const submitText = submitButton
      ? submitButton.querySelector('[data-submit-text]')
      : null;

    const originalButtonText = submitText
      ? submitText.textContent
      : submitButton
        ? submitButton.textContent
        : '';

    const t = translations[currentLang];

    if (submitButton && submitButton.disabled) return;

    if (!form.reportValidity()) return;

    const formData = new FormData(form);

    // Spam honeypot: if filled, do not send.
    if (formData.get('_honey')) return;

    const name = String(formData.get('name') || '').trim();
    const email = String(formData.get('email') || '').trim();
    const message = String(formData.get('message') || '').trim();

    if (!name || !email || !message) {
      showToast(t.toast_error);
      return;
    }

    if (submitButton) {
      submitButton.disabled = true;
      submitButton.setAttribute('aria-busy', 'true');
    }

    if (submitText) {
      submitText.textContent = t.form_sending;
    } else if (submitButton) {
      submitButton.textContent = t.form_sending;
    }

    try {
      const response = await fetch(
        'https://formsubmit.co/ajax/ismail1426419812@gmail.com',
        {
          method: 'POST',
          headers: {
            Accept: 'application/json'
          },
          body: new URLSearchParams({
            name,
            email,
            message,
            _subject: `New Portfolio Message from ${name}`,
            _template: 'table',
            _captcha: 'true'
          })
        }
      );

      let result;

      try {
        result = await response.json();
      } catch {
        result = null;
      }

      if (
        !response.ok ||
        !result ||
        !(
          result.success === true ||
          result.success === 'true'
        )
      ) {
        throw new Error(
          result?.message || `Request failed (${response.status})`
        );
      }

      showToast(t.toast_sent);
      form.reset();
    } catch (error) {
      console.error('Contact form submission failed:', error);

      showToast(
        error instanceof TypeError
          ? t.toast_network
          : t.toast_error
      );
    } finally {
      if (submitButton) {
        submitButton.disabled = false;
        submitButton.removeAttribute('aria-busy');
      }

      if (submitText) {
        submitText.textContent = originalButtonText || t.form_submit;
      } else if (submitButton) {
        submitButton.textContent = originalButtonText || t.form_submit;
      }
    }
  });
}

